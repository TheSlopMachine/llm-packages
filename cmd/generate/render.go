package main

import (
	"bytes"
	"encoding/json"
	"strconv"
	"strings"
	"text/template"
)

// scoopArchitectures maps Scoop architecture names to release platforms.
var scoopArchitectures = map[string]string{
	"64bit": "windows_amd64",
	"32bit": "windows_386",
	"arm64": "windows_arm64",
}

type scoopArchitecture struct {
	URL  string `json:"url"`
	Hash string `json:"hash"`
}

type scoopManifest struct {
	Version      string                       `json:"version"`
	Description  string                       `json:"description"`
	Homepage     string                       `json:"homepage"`
	License      string                       `json:"license"`
	Architecture map[string]scoopArchitecture `json:"architecture"`
	Bin          string                       `json:"bin"`
}

// renderScoop returns nil when the release has no Windows archive.
func renderScoop(release Release) ([]byte, error) {
	architectures := map[string]scoopArchitecture{}
	for scoopName, platform := range scoopArchitectures {
		if asset, ok := release.Assets[platform]; ok {
			architectures[scoopName] = scoopArchitecture{URL: asset.URL, Hash: asset.SHA256}
		}
	}
	if len(architectures) == 0 {
		return nil, nil
	}
	manifest := scoopManifest{
		Version:      release.Version,
		Description:  release.Description,
		Homepage:     release.Homepage,
		License:      release.License,
		Architecture: architectures,
		Bin:          release.Binary + ".exe",
	}
	data, err := json.MarshalIndent(manifest, "", "    ")
	if err != nil {
		return nil, err
	}
	return append(data, '\n'), nil
}

type formulaData struct {
	Release
	Class      string
	MacArm     *Asset
	MacIntel   *Asset
	LinuxArm   *Asset
	LinuxIntel *Asset
}

var formulaTemplate = template.Must(template.New("formula").Funcs(template.FuncMap{"ruby": rubyString}).Parse(
	`# Generated by cmd/generate from releases/{{.Name}}.json. Do not edit.
class {{.Class}} < Formula
  desc {{ruby .Description}}
  homepage {{ruby .Homepage}}
  version {{ruby .Version}}
  license {{ruby .License}}
{{- if or .MacArm .MacIntel}}

  on_macos do
{{- with .MacArm}}
    on_arm do
      url {{ruby .URL}}
      sha256 {{ruby .SHA256}}
    end
{{- end}}
{{- with .MacIntel}}
    on_intel do
      url {{ruby .URL}}
      sha256 {{ruby .SHA256}}
    end
{{- end}}
  end
{{- end}}
{{- if or .LinuxArm .LinuxIntel}}

  on_linux do
{{- with .LinuxArm}}
    on_arm do
      url {{ruby .URL}}
      sha256 {{ruby .SHA256}}
    end
{{- end}}
{{- with .LinuxIntel}}
    on_intel do
      url {{ruby .URL}}
      sha256 {{ruby .SHA256}}
    end
{{- end}}
  end
{{- end}}

  def install
    bin.install {{ruby .Binary}}
  end

  test do
    assert_predicate bin/{{ruby .Binary}}, :executable?
  end
end
`))

// renderFormula returns nil when the release has no macOS or 64-bit Linux archive.
func renderFormula(release Release) ([]byte, error) {
	data := formulaData{
		Release:    release,
		Class:      formulaClass(release.Name),
		MacArm:     assetPointer(release, "darwin_arm64"),
		MacIntel:   assetPointer(release, "darwin_amd64"),
		LinuxArm:   assetPointer(release, "linux_arm64"),
		LinuxIntel: assetPointer(release, "linux_amd64"),
	}
	if data.MacArm == nil && data.MacIntel == nil && data.LinuxArm == nil && data.LinuxIntel == nil {
		return nil, nil
	}
	var buffer bytes.Buffer
	if err := formulaTemplate.Execute(&buffer, data); err != nil {
		return nil, err
	}
	return buffer.Bytes(), nil
}

func assetPointer(release Release, platform string) *Asset {
	asset, ok := release.Assets[platform]
	if !ok {
		return nil
	}
	return &asset
}

// formulaClass converts a formula name to the Ruby class Homebrew expects: "llm-router" becomes "LlmRouter".
func formulaClass(name string) string {
	var builder strings.Builder
	for _, part := range strings.Split(name, "-") {
		if part == "" {
			continue
		}
		builder.WriteString(strings.ToUpper(part[:1]) + part[1:])
	}
	return builder.String()
}

// rubyString quotes a value as a Ruby double-quoted literal without interpolation.
func rubyString(value string) string {
	return strings.ReplaceAll(strconv.Quote(value), "#", `\#`)
}
